// Builds lib/icons.generated.ts: the Lucide icons (https://lucide.dev, ISC license) that stand in
// for Kwenta's emoji, as listed in lib/emoji-icons.json. Only those icons are copied in.
//
// Usage: node scripts/build-icons.mjs <path to the unpacked @iconify-json/lucide package>
//   (get it with: npm pack @iconify-json/lucide && tar -xzf iconify-json-lucide-*.tgz)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkgDir = process.argv[2];
if (!pkgDir) {
  console.error("Usage: node scripts/build-icons.mjs <@iconify-json/lucide package dir>");
  process.exit(1);
}
const lucide = JSON.parse(readFileSync(join(pkgDir, "icons.json"), "utf8"));
const map = JSON.parse(readFileSync(join("lib", "emoji-icons.json"), "utf8"));

const resolve = (name) => lucide.icons[name] ?? (lucide.aliases?.[name] ? lucide.icons[lucide.aliases[name].parent] : undefined);

const out = {};
const missing = [];
for (const [emoji, name] of Object.entries(map)) {
  if (emoji.startsWith("_")) continue;
  const icon = resolve(name);
  if (!icon) missing.push(`${emoji} → ${name}`);
  else out[name] = icon.body;
}
if (missing.length) {
  console.error("Unknown Lucide icon names:\n" + missing.join("\n"));
  process.exit(1);
}

writeFileSync(
  join("lib", "icons.generated.ts"),
  `// Generated by scripts/build-icons.mjs from Lucide (https://lucide.dev), ISC license. Do not edit by hand.\n` +
    `// Each value is the inside of a 24×24 SVG drawn with currentColor.\n` +
    `export const ICON_BODIES: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons`);
