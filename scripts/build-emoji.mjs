// Builds the country flag images (the currency picker's flags) from Circle Flags, MIT license:
// https://github.com/HatScripts/circle-flags
// Other emoji are drawn as Lucide icons instead (see scripts/build-icons.mjs and lib/emoji-icons.json).
//
// Usage: node scripts/build-emoji.mjs <unpacked @iconify-json/circle-flags package dir> <list file>
// The list file has one flag emoji per line (e.g. 🇵🇭). Non-flag lines are ignored.
// Writes public/emoji/<codepoints>.svg and lib/emoji.generated.ts (which flags have an image).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const [flagsDir, listFile] = process.argv.slice(2);
if (!flagsDir || !listFile) {
  console.error("Usage: node scripts/build-emoji.mjs <circle-flags package dir> <list file>");
  process.exit(1);
}
const flags = JSON.parse(readFileSync(join(flagsDir, "icons.json"), "utf8"));

/** "🇵🇭" → "ph": the two regional-indicator letters of a flag emoji. */
const flagCode = (e) => {
  const cps = [...e].map((c) => c.codePointAt(0));
  if (cps.length !== 2 || cps.some((cp) => cp < 0x1f1e6 || cp > 0x1f1ff)) return null;
  return cps.map((cp) => String.fromCharCode(cp - 0x1f1e6 + 97)).join("");
};
const key = (e) => [...e].map((c) => c.codePointAt(0).toString(16)).join("-");

const outDir = join("public", "emoji");
mkdirSync(outDir, { recursive: true });
const made = [];
const missing = [];
for (const e of readFileSync(listFile, "utf8").split(/\r?\n/).map((s) => s.trim()).filter(Boolean)) {
  const code = flagCode(e);
  if (!code) continue;
  const icon = flags.icons[code];
  if (!icon) {
    missing.push(e);
    continue;
  }
  const w = icon.width ?? flags.width ?? 512;
  const h = icon.height ?? flags.height ?? 512;
  writeFileSync(join(outDir, `${key(e)}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="32" height="32">${icon.body}</svg>`);
  made.push(key(e));
}
writeFileSync(
  join("lib", "emoji.generated.ts"),
  `// Generated by scripts/build-emoji.mjs. Do not edit by hand.\n` +
    `// Country flags that have an image in public/emoji (Circle Flags, MIT).\n` +
    `export const EMOJI_IMAGES = new Set<string>(${JSON.stringify(made.sort())});\n`,
);
console.log(`made ${made.length} flags${missing.length ? `, missing ${missing.join(" ")}` : ""}`);
