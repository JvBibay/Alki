// Imports app-icon logos (512px squares) into public/logos and refreshes lib/logos.generated.ts.
//
// Usage: npm run logos:import -- <folder>
//
// Each file in the folder is matched to a logo id by the table below, trimmed of any transparent
// margin, resized to 128px and saved as public/logos/<id>.app.png. The ".app" marks a full-bleed
// app icon: BankLogo shows it edge to edge, and `npm run logos` never replaces it. The old
// downloaded logo for the same id is removed.
import { readdirSync, unlinkSync, writeFileSync, existsSync } from "node:fs";
import { join, parse } from "node:path";
import sharp from "sharp";

/** File name (without extension) → logo id in lib/institutions.ts */
