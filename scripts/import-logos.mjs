  GCash: "gcash",
  GoTyme_Bank: "gotyme",
  Grab: "grabpay",
  Home_Credit_Philippines: "homecredit",
  LANDBANK_Mobile_Banking: "landbank",
  MariBank_PH_SeaBank: "maribank",
  Maya: "maya",
  Metrobank: "metrobank",
  MySSS: "sss",
  OwnBank: "ownbank",
  "Pag-IBIG_Fund_Virtual": "pagibig",
  PalawanPay: "palawanpay",
  PNB_Digital: "pnb",
